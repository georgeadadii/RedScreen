/**
 * Cross-language protocol vectors. The TypeScript implementation generates them from fixed
 * inputs; `npm test` checks the committed file still matches, and RedScreen's
 * `HintProtocolVectorTests` checks the Swift implementation against the same file.
 * All values are synthetic and carry an RSFAKE marker.
 */
import {
  base64url,
  canonicalJSON,
  clientProof,
  connectionKey,
  digestKey,
  messageTag,
  normalizeValue,
  seal,
  serverProof,
  valueDigest,
} from '../../src/protocol';
import type { RuleId } from '../../src/rules';

const sequence = (start: number, length: number) => Buffer.from(Array.from({ length }, (_, index) => (start + index) & 0xff));

export function generateVectors(): Record<string, unknown> {
  const secrets = { key: sequence(0x01, 32), sessionId: sequence(0xa0, 16) };
  const clientNonce = sequence(0x10, 16);
  const serverNonce = sequence(0x40, 16);
  const clientToServer = connectionKey(secrets, clientNonce, serverNonce, 'client-to-server');
  const serverToClient = connectionKey(secrets, clientNonce, serverNonce, 'server-to-client');
  const digest = digestKey(secrets);

  const values: [RuleId, string][] = [
    ['assignment.env', 'RSFAKE-pg-7d1c9a42'],
    ['assignment.env', '  "RSFAKE-quoted-0a1b"  '],
    ['connection-string.password', 'ＲSFAKE-fullwidth-42'],
    ['bearer.token', "'RSFAKE'inner'quote'"],
    ['assignment.credential', '`RSFAKE-backtick-77`'],
    ['provider.aws-access-key-id', 'AKIAIOSFODNN7EXAMPLE'],
    ['private-key.block', '-----BEGIN RSFAKE BLOCK-----\r\n    RSFAKEbody0123456789\r\n\r\n  -----END RSFAKE BLOCK-----  '],
    ['assignment.env', '\tRSFAKE-tab-padded\t'],
  ];

  const sent = 1_767_225_600_000;
  const body = {
    t: 'hints',
    v: 1,
    seq: 3,
    sent,
    expires: sent + 30_000,
    doc: base64url(sequence(0x70, 16)),
    hints: [{ rule: 'assignment.env', conf: 95, digest: valueDigest(digest, 'assignment.env', 'RSFAKE-pg-7d1c9a42') }],
  };
  const ready = { t: 'ready', v: 1, seq: 0 };
  const ack = { t: 'ack', v: 1, seq: 1, accepted: 1 };

  return {
    description: 'Generated by Extensions/vscode/test/support/vectors.ts. Do not edit by hand.',
    inputs: {
      key: base64url(secrets.key),
      session: base64url(secrets.sessionId),
      clientNonce: base64url(clientNonce),
      serverNonce: base64url(serverNonce),
    },
    serverProof: base64url(serverProof(secrets, clientNonce, serverNonce)),
    clientProof: base64url(clientProof(secrets, clientNonce, serverNonce)),
    clientToServerKey: base64url(clientToServer),
    serverToClientKey: base64url(serverToClient),
    digestKey: base64url(digest),
    digests: values.map(([rule, value]) => ({ rule, value, normalized: normalizeValue(value), digest: valueDigest(digest, rule, value) })),
    canonical: [
      { value: { b: 1, a: [{ d: 2, c: 'x"\\\n\u0001' }], e: true, f: null }, json: canonicalJSON({ b: 1, a: [{ d: 2, c: 'x"\\\n\u0001' }], e: true, f: null }) },
      { value: body, json: canonicalJSON(body) },
    ],
    frames: {
      hints: { json: seal(clientToServer, body).toString('utf8'), key: 'clientToServer' },
      ready: { json: seal(serverToClient, ready).toString('utf8'), key: 'serverToClient', tag: messageTag(serverToClient, ready) },
      ack: { json: seal(serverToClient, ack).toString('utf8'), key: 'serverToClient', tag: messageTag(serverToClient, ack) },
    },
  };
}

if (require.main === module) {
  // `npm run vectors` rewrites test/fixtures/protocol-vectors.json.
  const { writeFileSync } = require('node:fs') as typeof import('node:fs');
  const { join } = require('node:path') as typeof import('node:path');
  const path = join(__dirname, '..', '..', '..', 'test', 'fixtures', 'protocol-vectors.json');
  writeFileSync(path, `${JSON.stringify(generateVectors(), null, 2)}\n`);
}
